-- Catalogo Virtual Cipolatti: paginas WebP geradas a partir dos PDFs.
BEGIN;

CREATE TABLE IF NOT EXISTS comercial.tema_pdf_pagina (
    idtema_pdf_pagina bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idtema_pdf bigint NOT NULL,
    numero_pagina integer NOT NULL,
    arquivo_imagem character varying(500) NOT NULL,
    largura integer,
    altura integer,
    tamanho_bytes bigint,
    data_cadastro timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT uq_tema_pdf_pagina_numero UNIQUE (idtema_pdf, numero_pagina),
    CONSTRAINT fk_tema_pdf_pagina_pdf FOREIGN KEY (idtema_pdf)
        REFERENCES comercial.tema_pdf(idtema_pdf),
    CONSTRAINT ck_tema_pdf_pagina_numero CHECK (numero_pagina > 0),
    CONSTRAINT ck_tema_pdf_pagina_arquivo CHECK (btrim(arquivo_imagem) <> ''),
    CONSTRAINT ck_tema_pdf_pagina_largura CHECK (largura IS NULL OR largura > 0),
    CONSTRAINT ck_tema_pdf_pagina_altura CHECK (altura IS NULL OR altura > 0),
    CONSTRAINT ck_tema_pdf_pagina_tamanho CHECK (tamanho_bytes IS NULL OR tamanho_bytes >= 0)
);

-- A constraint UNIQUE ja fornece indice para (idtema_pdf, numero_pagina).
COMMENT ON TABLE comercial.tema_pdf_pagina IS
    'Metadados das paginas WebP processadas de cada PDF.';
COMMENT ON COLUMN comercial.tema_pdf_pagina.arquivo_imagem IS
    'Path relativo no storage; a imagem nao e armazenada no PostgreSQL.';

COMMIT;

