BEGIN;

CREATE TABLE IF NOT EXISTS comercial.tema_capa (
    idtema_capa bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idtema integer NOT NULL,
    arquivo_imagem character varying(500) NOT NULL,
    ordem integer NOT NULL DEFAULT 0,
    ativo boolean NOT NULL DEFAULT true,
    inserido_por character varying(200),
    data_cadastro timestamp without time zone NOT NULL DEFAULT now(),
    alterado_por character varying(200),
    data_altera timestamp without time zone,
    CONSTRAINT fk_tema_capa_tema FOREIGN KEY (idtema) REFERENCES comercial.temas(idtema),
    CONSTRAINT ck_tema_capa_arquivo CHECK (btrim(arquivo_imagem) <> ''),
    CONSTRAINT ck_tema_capa_ordem CHECK (ordem >= 0)
);

CREATE INDEX IF NOT EXISTS ix_tema_capa_tema_ativo_ordem
    ON comercial.tema_capa(idtema, ativo, ordem, idtema_capa);

CREATE UNIQUE INDEX IF NOT EXISTS uq_tema_capa_arquivo_ativo
    ON comercial.tema_capa(idtema, arquivo_imagem) WHERE ativo = true;

INSERT INTO comercial.tema_capa(idtema, arquivo_imagem, ordem, ativo, inserido_por)
SELECT tc.idtema, tc.imagem_capa, 0, true, 'migracao-012'
FROM comercial.tema_catalogo tc
WHERE NULLIF(btrim(tc.imagem_capa), '') IS NOT NULL
  AND NOT EXISTS (
    SELECT 1 FROM comercial.tema_capa c
    WHERE c.idtema = tc.idtema AND c.arquivo_imagem = tc.imagem_capa AND c.ativo = true
  );

COMMIT;
