-- Catalogo Virtual Cipolatti: multiplos videos YouTube por tema.
BEGIN;

CREATE TABLE IF NOT EXISTS comercial.tema_video (
    idtema_video bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idtema integer NOT NULL,
    titulo character varying(200) NOT NULL,
    descricao text,
    youtube_video_id character varying(32),
    youtube_url character varying(500),
    thumbnail_url character varying(500),
    ordem integer NOT NULL DEFAULT 0,
    ativo boolean NOT NULL DEFAULT true,
    status character varying(20) NOT NULL DEFAULT 'pending',
    privacy_status character varying(20),
    mensagem_erro text,
    inserido_por character varying(120),
    data_cadastro timestamp with time zone NOT NULL DEFAULT now(),
    alterado_por character varying(120),
    data_altera timestamp with time zone,
    CONSTRAINT ck_tema_video_titulo CHECK (btrim(titulo) <> ''),
    CONSTRAINT ck_tema_video_ordem CHECK (ordem >= 0),
    CONSTRAINT ck_tema_video_status
        CHECK (status IN ('pending', 'uploading', 'processing', 'ready', 'error')),
    CONSTRAINT ck_tema_video_privacy
        CHECK (privacy_status IS NULL OR privacy_status IN ('public', 'unlisted', 'private')),
    CONSTRAINT fk_tema_video_tema FOREIGN KEY (idtema)
        REFERENCES comercial.temas(idtema)
);

CREATE INDEX IF NOT EXISTS ix_tema_video_tema_ativo_ordem
    ON comercial.tema_video (idtema, ativo, ordem, idtema_video);

CREATE UNIQUE INDEX IF NOT EXISTS uq_tema_video_youtube_id
    ON comercial.tema_video (youtube_video_id)
    WHERE youtube_video_id IS NOT NULL;

COMMENT ON TABLE comercial.tema_video IS
    'Metadados dos videos associados aos temas do Catalogo Virtual.';

COMMIT;

