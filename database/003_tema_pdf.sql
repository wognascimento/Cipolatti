-- Catalogo Virtual Cipolatti: multiplas apresentacoes PDF por tema.
BEGIN;

CREATE TABLE IF NOT EXISTS comercial.tema_pdf (
    idtema_pdf bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idtema integer NOT NULL,
    titulo character varying(200) NOT NULL,
    descricao text,
    arquivo_original character varying(500) NOT NULL,
    ordem integer NOT NULL DEFAULT 0,
    ativo boolean NOT NULL DEFAULT true,
    principal boolean NOT NULL DEFAULT false,
    permitir_download boolean NOT NULL DEFAULT false,
    quantidade_paginas integer,
    status character varying(20) NOT NULL DEFAULT 'pending',
    mensagem_erro text,
    inserido_por character varying(120),
    data_cadastro timestamp with time zone NOT NULL DEFAULT now(),
    alterado_por character varying(120),
    data_altera timestamp with time zone,
    CONSTRAINT ck_tema_pdf_titulo CHECK (btrim(titulo) <> ''),
    CONSTRAINT ck_tema_pdf_arquivo_original CHECK (btrim(arquivo_original) <> ''),
    CONSTRAINT ck_tema_pdf_ordem CHECK (ordem >= 0),
    CONSTRAINT ck_tema_pdf_status
        CHECK (status IN ('pending', 'processing', 'ready', 'error')),
    CONSTRAINT ck_tema_pdf_quantidade_paginas
        CHECK (quantidade_paginas IS NULL OR quantidade_paginas > 0),
    CONSTRAINT fk_tema_pdf_tema FOREIGN KEY (idtema)
        REFERENCES comercial.temas(idtema)
);

CREATE INDEX IF NOT EXISTS ix_tema_pdf_tema_ativo_ordem
    ON comercial.tema_pdf (idtema, ativo, ordem, idtema_pdf);

-- Garante no maximo um PDF simultaneamente ativo e principal por tema.
CREATE UNIQUE INDEX IF NOT EXISTS uq_tema_pdf_principal_ativo
    ON comercial.tema_pdf (idtema)
    WHERE principal = true AND ativo = true;

COMMENT ON TABLE comercial.tema_pdf IS
    'Metadados das apresentacoes PDF do Catalogo Virtual.';
COMMENT ON COLUMN comercial.tema_pdf.arquivo_original IS
    'Path relativo no storage; o PDF nao e armazenado no PostgreSQL.';

COMMIT;

