-- Catalogo Virtual Cipolatti: credencial protegida do canal e uploads retomaveis.
-- NAO armazena access token. refresh_token e session_uri chegam protegidos pela API.
BEGIN;

CREATE TABLE IF NOT EXISTS comercial.youtube_integracao (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    canal_id character varying(100) NOT NULL,
    canal_nome character varying(200) NOT NULL,
    conta_email character varying(320),
    refresh_token_protegido text NOT NULL,
    ativo boolean NOT NULL DEFAULT true,
    data_autorizacao timestamp with time zone NOT NULL DEFAULT now(),
    data_atualizacao timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT uq_youtube_integracao_canal UNIQUE (canal_id)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_youtube_integracao_ativa
    ON comercial.youtube_integracao (ativo) WHERE ativo = true;

CREATE TABLE IF NOT EXISTS comercial.youtube_upload (
    idyoutube_upload bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idtema_video bigint NOT NULL,
    arquivo_local character varying(500) NOT NULL,
    content_type character varying(100) NOT NULL,
    tamanho_bytes bigint NOT NULL,
    bytes_enviados bigint NOT NULL DEFAULT 0,
    session_uri_protegida text,
    tentativas integer NOT NULL DEFAULT 0,
    proxima_tentativa timestamp with time zone,
    status character varying(20) NOT NULL DEFAULT 'pending',
    mensagem_erro text,
    data_cadastro timestamp with time zone NOT NULL DEFAULT now(),
    data_altera timestamp with time zone,
    CONSTRAINT fk_youtube_upload_video FOREIGN KEY (idtema_video)
        REFERENCES comercial.tema_video(idtema_video),
    CONSTRAINT uq_youtube_upload_video UNIQUE (idtema_video),
    CONSTRAINT ck_youtube_upload_tamanho CHECK (tamanho_bytes > 0),
    CONSTRAINT ck_youtube_upload_bytes CHECK (bytes_enviados >= 0 AND bytes_enviados <= tamanho_bytes),
    CONSTRAINT ck_youtube_upload_tentativas CHECK (tentativas >= 0),
    CONSTRAINT ck_youtube_upload_status CHECK
        (status IN ('pending','uploading','processing','ready','error'))
);

CREATE INDEX IF NOT EXISTS ix_youtube_upload_fila
    ON comercial.youtube_upload (status, proxima_tentativa, data_cadastro);

COMMENT ON TABLE comercial.youtube_integracao IS
    'Canal YouTube autorizado. O refresh token e persistido somente em formato protegido.';
COMMENT ON TABLE comercial.youtube_upload IS
    'Estado persistente de uploads resumiveis; session_uri tambem deve ser protegida.';

COMMIT;
